// Generates src/lib/api/schema.d.ts from the backend's OpenAPI spec. Run with `npm run api:types`
// after the backend changelog lists a change.
//
// The spec writes an "any value" schema as `[]` (PHP's empty array) where OpenAPI expects
// `{}`. The generator refuses that, so those are turned into `{}` first.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(import.meta.dirname, "..");
const source = process.argv[2] ?? join(root, "..", "bf-backend", "cms", "docs", "openapi.json");
const target = join(root, "src", "lib", "api", "schema.d.ts");

/** Keys whose value really is a list. An empty list anywhere else stands for "any schema". */
const LISTS = new Set(["required", "enum", "parameters", "tags", "security", "servers", "oneOf", "anyOf", "allOf", "type", "x-resources", "examples"]);

function repair(node, key) {
  if (Array.isArray(node)) {
    if (node.length === 0 && !LISTS.has(key)) return {};
    return node.map((entry) => repair(entry, key));
  }
  if (node && typeof node === "object") {
    return Object.fromEntries(Object.entries(node).map(([name, value]) => [name, repair(value, name)]));
  }
  return node;
}

const spec = repair(JSON.parse(readFileSync(source, "utf8")), "");
const ast = await openapiTS(spec);
const header = "// Generated by `npm run api:types` from bf-backend/cms/docs/openapi.json. Do not edit by hand.\n\n";
writeFileSync(target, header + astToString(ast));
console.log(`Wrote ${target}`);
